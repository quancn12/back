"""docs/human/API.md must list exactly the routes the app serves.

The specification is generated by scripts/export_api_docs.py from the app and
from real calls recorded by scripts/capture_api_examples.py. A route added or
removed without regenerating both fails here; so does a recorded example that
leaks a secret or silently records a failure.
"""
from __future__ import annotations

import importlib.util
import json
import re
import unittest
from pathlib import Path

from fastapi.routing import APIRoute
from fastapi.testclient import TestClient

import app.main as main

ROOT = Path(__file__).resolve().parents[1]
REFERENCE = (ROOT / "docs" / "human" / "API.md").read_text(encoding="utf-8")
EXAMPLES = json.loads((ROOT / "scripts" / "api_examples.json").read_text(encoding="utf-8"))
_spec = importlib.util.spec_from_file_location("export_api_docs", ROOT / "scripts" / "export_api_docs.py")
export_api_docs = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(export_api_docs)
KNOWN_BROKEN = {"POST /api/hotels/{slug}/chat/stream"}  # started/prepared undefined, app/api/chat.py


def served_routes() -> set[str]:
    keys = set()
    for route in export_api_docs._api_routes(main.app.routes, APIRoute):
        for method in route.methods - {"HEAD", "OPTIONS"}:
            keys.add(f"{method} {route.path.replace('{asset_path:path}', '{asset_path}')}")
    return keys


class ApiReferenceTests(unittest.TestCase):
    def setUp(self):
        self.documented = set(re.findall(r"^\* \*\*Endpoint:\*\* `([A-Z]+ [^`]+)`$", REFERENCE, re.M))
        # Legacy Hotel routes are served only with HOTEL_MODE_ENABLED=true.
        self.legacy = {key for key in self.documented if key.split(" ", 1)[1].startswith(("/api/hotels", "/hotel-chat"))}

    def test_every_served_route_is_documented_with_a_real_example(self):
        missing = served_routes() - self.documented
        self.assertFalse(missing, f"Run python scripts/export_api_docs.py; missing: {sorted(missing)}")
        unrecorded = served_routes() - set(EXAMPLES)
        self.assertFalse(unrecorded, f"Run python scripts/capture_api_examples.py; unrecorded: {sorted(unrecorded)}")
        self.assertEqual(len(re.findall(r"^\| \*\*[IVXLC]+\*\* \|", REFERENCE, re.M)), len(self.documented), "catalogue and details agree")

    def test_no_documented_route_is_gone(self):
        # Legacy Hotel routes exist only with HOTEL_MODE_ENABLED=true.
        gone = self.documented - served_routes() - self.legacy
        self.assertFalse(gone, f"Documented but not served: {sorted(gone)}")
        self.assertEqual(self.documented, set(export_api_docs.ROUTES))
        self.assertTrue(all(key.split(" ", 1)[1].startswith(("/api/hotels", "/hotel-chat")) for key in self.legacy))

    def test_recorded_examples_succeeded_and_hide_secrets(self):
        for key, examples in EXAMPLES.items():
            if key == "_errors":
                continue
            for example in examples:
                with self.subTest(route=key):
                    if key in KNOWN_BROKEN:
                        self.assertEqual(example["status"], 500)
                    else:
                        self.assertLess(example["status"], 400, example.get("response"))
        text = json.dumps(EXAMPLES, ensure_ascii=False)
        self.assertNotIn(export_api_docs.__dict__.get("ADMIN_KEY", "vi-du-khoa-admin"), text)
        for secret in re.findall(r'"(?:csrf_token|access_token|api_key|token)": "([^"]*)"', text):
            self.assertLessEqual(len(secret), 13, f"unmasked secret: {secret[:16]}")
        for pin in re.findall(r'"pin": "([^"]*)"', text):
            self.assertRegex(pin, r"^\d{2}…$", "PINs keep two digits only")
        self.assertNotRegex(text, r"(state|nonce)=[^&…\"]{7,}")
        self.assertEqual({e["label"] for e in EXAMPLES["_errors"]}, {"422", "404", "403", "401-admin", "401-partner"})

    def test_recorded_shapes_match_the_live_app(self):
        client = TestClient(main.app)
        self.assertEqual(client.get("/api/health/live").json(), EXAMPLES["GET /api/health/live"][0]["response"])
        self.assertEqual(set(client.get("/api/info").json()), set(EXAMPLES["GET /api/info"][0]["response"]))
        self.assertEqual(set(client.get("/api/v1/proactive/availability").json()),
                         set(EXAMPLES["GET /api/v1/proactive/availability"][0]["response"]))
        self.assertEqual(client.get("/api/v1/stays/active").json(), {"active": False, "stay": None})
        self.assertIn("VietSage **không bọc** response trong envelope", REFERENCE)


if __name__ == "__main__":
    unittest.main()
